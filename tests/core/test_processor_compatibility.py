"""The processor and model compatibility page matches the code.

``docs/api/processors/compatibility.rst`` is generated by
``tests/core/processor_compatibility_utils.py``. Every pairing it marks ✓ must still
run, and the embedding column must match what ``EmbeddingModel`` builds. A
pairing marked ✗ that now runs is allowed; rerun the tool to update the
page.
"""

import unittest
import warnings

from tests.core import processor_compatibility_utils as tool


class TestCompatibilityPage(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.page = tool.read_page(tool.PAGE.read_text(encoding="utf-8"))

    def setUp(self):
        # Silence the models' warnings for this test only.
        self._warnings = warnings.catch_warnings()
        self._warnings.__enter__()
        warnings.simplefilter("ignore")
        self.addCleanup(self._warnings.__exit__, None, None, None)

    def test_page_lists_every_probed_processor_and_model(self):
        self.assertEqual(list(self.page), tool.PROCESSORS)
        for row in self.page.values():
            self.assertEqual(list(row)[1:], tool.MODELS)

    def test_embedding_column_matches_embedding_model(self):
        for key, row in self.page.items():
            with self.subTest(processor=key):
                layer = tool.embedding_layer(tool.sample_dataset(key))
                self.assertEqual(row["Embedding"],
                                 tool._EMBEDDING_TEXT.get(layer, layer))

    def test_every_pairing_marked_working_runs(self):
        for key, row in self.page.items():
            working = [m for m in tool.MODELS if row[m] == "✓"]
            if not working:
                continue
            dataset = tool.sample_dataset(key)
            for name in working:
                with self.subTest(processor=key, model=name):
                    ok, error = tool.runs(dataset, name)
                    self.assertTrue(ok, f"{key} + {name}: {error}. If this is "
                                    "intended, rerun python -m "
                                    "tests.core.processor_compatibility_utils")

    def test_render_and_read_round_trip(self):
        results = {"sequence": {"embedding": "Embedding",
                                **{m: (m != "CNN", "") for m in tool.MODELS}}}
        page = tool.read_page(tool.render(results))
        self.assertEqual(page["sequence"]["Embedding"], "``nn.Embedding``")
        self.assertEqual(page["sequence"]["CNN"], "✗")
        self.assertEqual(page["sequence"]["RNN"], "✓")


if __name__ == "__main__":
    unittest.main()
